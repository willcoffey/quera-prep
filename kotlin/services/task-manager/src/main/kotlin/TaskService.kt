/**
 * Business logic for the TaskManager
 *
 * Only ever triggered by the TaskManager files. Sources of triggers
 * can be
 *
 * - API Requests
 * - Pulsar Listeners
 * - Scheduled outbox draining
 *
 */
package taskmanager

import org.springframework.jdbc.core.simple.JdbcClient
import org.springframework.stereotype.Service
import kotlin.jvm.optionals.getOrNull
import org.springframework.transaction.annotation.Transactional
import org.springframework.dao.DataIntegrityViolationException
import org.springframework.transaction.interceptor.TransactionAspectSupport


@Service
class TaskService(private val db: JdbcClient) {

    /**
     * Inserts records into programs, tasks, and the outbox in a single
     * atomic transaction. If the task already exists in the database it
     * does not create the messages for running jobs and simply returns
     * the existing taskId.
     */
    @Transactional
    fun insertOrFind(input: CreateTaskBody): InsertResult? {
        // throws when the program hash doesn't match the programId. postgres
        // constraint. Catch here so the rest controller can stay storage 
        // agnostic and have a simple when statement
        try {
            insertProgram(input)
        } catch (e: DataIntegrityViolationException) {
            TransactionAspectSupport.currentTransactionStatus().setRollbackOnly()
            return null
        }
        val taskId = insertTask(input)
        if (taskId == null) {
            // A new taskId wasn't generated, so it must already exist
            // Find the existing task and return its details
            return findByIdemKey(input.idemKey)
        } else {
            // The task was created, create the run messages and return
            enqueueRuns(taskId, input)
            return InsertResult(taskId, null)
        }
    }

    /**
     * Insert program into database or do nothing. Doing nothing is fine
     * since programs are content addressed.
     */
    private fun insertProgram(input: CreateTaskBody) {
        val stmt = db.sql(
            """
            INSERT INTO programs (program_id, body)
            VALUES (:program_id, :body)
            ON CONFLICT (program_id) DO NOTHING
            """
        )
        stmt.param("program_id", input.programId)
            .param("body", input.commands.joinToString("\n"))
            .update()
    }

    /**
     * Inserts the task or returns null on conflict. null implies the task
     * already exists, so we will need to look it up to get the taskId
     */
    private fun insertTask(input: CreateTaskBody): Long? {
        val stmt = db.sql(
            """
            INSERT INTO task (idem_key, program_id, runs)
            VALUES (:idem_key, :program_id, :runs)
            ON CONFLICT (idem_key) DO NOTHING
            RETURNING task_id
            """
        )
        val taskId = stmt.param("idem_key", input.idemKey)
            .param("program_id", input.programId)
            .param("runs", input.runs)
            .query(Long::class.java)
            .optional()
            .getOrNull()
        return taskId
    }

    /**
     * Used when inserting a task fails due to conflict. Since taskId is
     * generated by the database, we need to look it up via idemKey to
     * get the task associated with this idemKey
     */
    private fun findByIdemKey(idemKey: String): InsertResult {
        val stmt = db.sql(
            """
            SELECT task_id, program_id
            FROM task
            WHERE idem_key = :idem_key
            """
        )
        val existing = stmt
            .param("idem_key", idemKey)
            .query { rs, _ -> InsertResult(rs.getLong(1), rs.getString(2)) }
            .single()
        return existing
    }

    /**
     * Creates n messages in the outbox so that they can be later drained
     * into pulsar. Each job gets its own message which can be useful for
     * distributing to replicas and in the future for managing fairness such
     * as round-robin.
     */
    private fun enqueueRuns(taskId: Long, input: CreateTaskBody) {
        val stmt = db.sql(
            """
            INSERT INTO outbox (task_id, program_id)
            SELECT :task_id, :program_id FROM generate_series(1, :runs)
            """
        )
        stmt.param("task_id", taskId)
            .param("program_id", input.programId)
            .param("runs", input.runs)
            .update()
    }
}

data class InsertResult(val taskId: Long, val existingProgramId: String?)
