#!/usr/bin/env bash
# Run the full stack with one kotlin service in dev mode (gradle + hot reload).
#
# usage: ./dev.ai.sh <service> [extra `compose up` args]
#
# Generates .dev/compose.<service>.yaml, an override that swaps the service's
# image for the Dockerfile `dev` stage, bind mounts the kotlin source, and runs
# a continuous compile alongside bootRun so devtools restarts on change. All
# other services run from their normal built images. Also generates
# .dev/dev.init.gradle.kts, the gradle init script the dev container uses.
#
# Set COMPOSE to change the compose command, e.g. COMPOSE="docker compose".
# JVM settings for the dev container (see below) can be overridden the same way.

# Re-exec under bash if invoked via `sh dev.ai.sh` (dash on debian).
if [ -z "${BASH_VERSION:-}" ]; then exec bash "$0" "$@"; fi
set -euo pipefail

usage() {
  echo "usage: $0 <service> [compose up args...]" >&2
  echo "services: $(ls "$ROOT/kotlin/services" | tr '\n' ' ')" >&2
  exit 1
}

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
COMPOSE="${COMPOSE:-podman compose}"

[[ $# -ge 1 ]] || usage
SERVICE="$1"
shift

if [[ ! -d "$ROOT/kotlin/services/$SERVICE" ]]; then
  echo "error: no service dir kotlin/services/$SERVICE" >&2
  usage
fi
if ! grep -qE "^  $SERVICE:" "$ROOT/compose.yaml"; then
  echo "error: service '$SERVICE' not defined in compose.yaml" >&2
  exit 1
fi

OVERRIDE_DIR="$ROOT/.dev"
OVERRIDE="$OVERRIDE_DIR/compose.$SERVICE.yaml"
INIT_SCRIPT="$OVERRIDE_DIR/dev.init.gradle.kts"
mkdir -p "$OVERRIDE_DIR"

# JVM settings, dev container only. Both gradle runs use --no-daemon: the
# gradlew client forks a single-use daemon that exits with it, so no daemon
# outlives its build or piles up in the gradle-cache registry.
#   DEV_CLIENT_JVM  both gradlew clients, which only relay output
#   DEV_WATCH_JVM   continuous build daemon, also compiles kotlin in process
#   DEV_RUN_JVM     bootRun daemon, idles while the app runs
# The app itself takes JAVA_TOOL_OPTIONS from compose.yaml, same as prod-like
# runs. The gradle JVMs see it too, but their own flags take precedence.
: "${DEV_WATCH_JVM:=-Xms64m -Xmx384m -XX:MaxMetaspaceSize=512m \
-XX:+UseSerialGC -XX:TieredStopAtLevel=1 -XX:ReservedCodeCacheSize=128m}"
: "${DEV_CLIENT_JVM:=-Xms16m -Xmx64m -XX:+UseSerialGC \
-XX:TieredStopAtLevel=1}"
: "${DEV_RUN_JVM:=-Xms64m -Xmx160m -XX:MaxMetaspaceSize=384m \
-XX:+UseSerialGC -XX:TieredStopAtLevel=1}"

# Paths are absolute so they don't depend on how the compose provider resolves
# relative paths in secondary -f files.
#
# Anonymous volumes over .gradle, .kotlin and build/ keep the container's build
# state separate from any gradle / LSP running on the host.
#
# The entrypoint starts the continuous build first and bootRun once it has
# staged a build, see the init script below. bootRun depends on no compile
# task, so only the watcher compiles. If either gradle process exits the
# container stops, rather than leaving the app running without hot reload.
# `init: true` forwards stop signals to bash.
#
# The first part is expanded here, the entrypoint is literal ($$ is compose's
# escape for $).
cat > "$OVERRIDE" <<EOF
# Generated by dev.ai.sh, do not edit. Regenerated on every run.
services:
  $SERVICE:
    image: localhost/$SERVICE:dev
    build:
      target: dev
    volumes:
      - "$ROOT/kotlin:/workspace"
      - "$INIT_SCRIPT:/dev-init/dev.init.gradle.kts:ro"
      - gradle-cache:/gradle
      - /workspace/.gradle
      - /workspace/.kotlin
      - /workspace/services/$SERVICE/build
    init: true
    environment:
      DEV_SERVICE: "$SERVICE"
      DEV_WATCH_JVM: "$DEV_WATCH_JVM"
      DEV_CLIENT_JVM: "$DEV_CLIENT_JVM"
      DEV_RUN_JVM: "$DEV_RUN_JVM"
EOF
cat >> "$OVERRIDE" <<'EOF'
    entrypoint: ["bash", "-c"]
    command:
      - |
        set -u
        p=:services:$$DEV_SERVICE
        trigger=services/$$DEV_SERVICE/build/dev/trigger/restart.trigger
        session=$$(date +%s%N)
        # gradle <GRADLE_OPTS> <org.gradle.jvmargs> <args>, run in the
        # background. exec makes the job's pid gradlew's java client, so
        # killing the job cancels the build. MALLOC_ARENA_MAX caps glibc's
        # per-thread malloc arenas, which otherwise keep memory the JVM freed.
        gradle() {
          MALLOC_ARENA_MAX=2 GRADLE_OPTS="$$1" exec ./gradlew --no-daemon \
            -Dorg.gradle.jvmargs="$$2" -I /dev-init/dev.init.gradle.kts \
            -PdevProject=$$p -PdevSession=$$session "$${@:3}"
        }
        trap 'exit 143' TERM INT
        trap 'kill $$(jobs -p) 2>/dev/null; wait' EXIT
        echo "[dev] waiting for the first successful build"
        gradle "$$DEV_CLIENT_JVM" "$$DEV_WATCH_JVM" \
          -Pkotlin.compiler.execution.strategy=in-process \
          --continuous $$p:devTrigger &
        until grep -qs "^$$session " "$$trigger"; do
          kill -0 $$! 2>/dev/null || exit 1
          sleep 1
        done
        gradle "$$DEV_CLIENT_JVM" "$$DEV_RUN_JVM" $$p:bootRun &
        wait -n
        echo "[dev] a gradle process exited, stopping $$DEV_SERVICE" >&2
        exit 1
volumes:
  gradle-cache:
EOF

# Restart flow, per successful build:
#   compileKotlin etc.  write build/classes as usual
#   devSync             copies the build output to build/dev/classpath,
#                       bootRun's classpath instead of build/classes. Files are
#                       rewritten in place, so the running app may see a mixed
#                       set during this copy, never during the compile, and
#                       the restart that follows replaces it. After the first
#                       build it waits until the app has logged "Started":
#                       devtools only sees trigger changes once its watcher is
#                       up, so a build staged while the app starts would never
#                       restart it. Edits made meanwhile give one restart.
#   devTrigger          writes build/dev/trigger/restart.trigger. Up to date,
#                       so skipped, unless the staged output or the session
#                       (new per container start) changed
#   devtools            restarts only when restart.trigger changes
# A failed compile stops before devSync, so the running app is left alone.
cat > "$INIT_SCRIPT" <<'EOF'
// Generated by dev.ai.sh, do not edit. Regenerated on every run.
//
// Dev mode wiring for the project named by -PdevProject, see dev.ai.sh.
// -PdevSession changes per container start so the first devTrigger run always
// writes the trigger, which the entrypoint waits on before starting bootRun.
// The trigger and started files hold the session so stale ones from a previous
// start are never mistaken for this one.

import java.time.Instant

// Passes bootRun's output through and acts on the app's "Started X in" lines.
//
// First start: writes the session to the started file, which devSync waits on
// before staging any build after the first.
//
// Restarts: report the time since the source edit behind the restart. If a
// second build writes the trigger before a restart logs "Started", that
// restart is reported with the second build's times and the second restart is
// not reported.
class AppOutput(
  private val trigger: File,
  private val startedFile: File,
  private val session: String,
) : java.io.OutputStream() {
  companion object {
    fun secs(ms: Long) = "%.2fs".format(ms / 1000.0)
  }

  private val started = Regex(" Started \\S+ in ")
  private val line = java.io.ByteArrayOutputStream()
  private var timed: String? = null

  override fun write(b: Int) {
    System.out.write(b)
    if (b != '\n'.code) {
      line.write(b)
      return
    }
    val text = line.toString(Charsets.UTF_8)
    line.reset()
    if (started.containsMatchIn(text)) report()
  }

  override fun flush() = System.out.flush()

  // Never throws, that would break bootRun's output forwarding.
  private fun report() {
    runCatching {
      val stamp = trigger.readText().trim()
      if (timed == null) {
        timed = stamp
        startedFile.writeText("$session\n")
        return
      }
      if (stamp == timed) return
      timed = stamp
      val (edit, ready) = stamp.split(" ").drop(1).map(String::toLong)
      val now = System.currentTimeMillis()
      println("[dev] restarted ${secs(now - edit)} after source edit " +
        "(build ${secs(ready - edit)}, restart ${secs(now - ready)})")
    }
  }
}

val devProject = gradle.startParameter.projectProperties["devProject"]

if (devProject != null) allprojects {
  if (path != devProject) return@allprojects
  pluginManager.withPlugin("org.springframework.boot") {
    val main = the<SourceSetContainer>()["main"]
    val stageDir = layout.buildDirectory.dir("dev/classpath")
    val triggerDir = layout.buildDirectory.dir("dev/trigger")
    val triggerFile = triggerDir.map { it.file("restart.trigger") }
    val session = providers.gradleProperty("devSession").getOrElse("")
    val sources = layout.projectDirectory.dir("src/main").asFile
    val startedFile = layout.buildDirectory.file("dev/started")

    val devSync = tasks.register<Sync>("devSync") {
      from(main.output)
      into(stageDir)
      // After the first build, wait for the app's first "Started", see the
      // restart flow in dev.ai.sh. The poll only adds latency.
      doFirst {
        fun holdsSession(file: File) = file.exists() &&
          file.readText().trim().substringBefore(' ') == session
        val started = startedFile.get().asFile
        if (!holdsSession(triggerFile.get().asFile) || holdsSession(started)) {
          return@doFirst
        }
        println("[dev] build waiting for the app to start")
        while (!holdsSession(started)) Thread.sleep(500)
      }
    }

    tasks.register("devTrigger") {
      inputs.files(devSync).withPropertyName("staged")
      inputs.property("session", session)
      outputs.file(triggerFile)
      doLast {
        val now = System.currentTimeMillis()
        // Newest mtime of any source file or dir, dirs catch deletes. Read
        // when the build ends, so after a save during the build the reported
        // time is too short; the build that save triggers reports it.
        val edit = sources.walk().maxOfOrNull { it.lastModified() } ?: now
        val file = triggerFile.get().asFile
        val startup = !file.exists() || !file.readText().startsWith("$session ")
        file.writeText("$session $edit $now\n")
        if (startup) {
          println("[dev] classes staged for startup")
          return@doLast
        }
        val since = AppOutput.secs(now - edit)
        println("[dev] classes staged ${Instant.ofEpochMilli(now)}, " +
          "$since after source edit at ${Instant.ofEpochMilli(edit)}")
      }
    }

    // afterEvaluate so this runs after the boot plugin's own setup. Main class
    // lookup and bootRun both use the staged classes, so neither depends on a
    // compile task or reads build/classes while the watcher writes it.
    afterEvaluate {
      tasks.named("resolveMainClassName") {
        setProperty("classpath", files(stageDir))
      }
      tasks.named<JavaExec>("bootRun") {
        classpath = files(stageDir, triggerDir) +
          configurations["runtimeClasspath"]
        systemProperty(
          "spring.devtools.restart.trigger-file", "restart.trigger")
        standardOutput = AppOutput(triggerFile.get().asFile,
          startedFile.get().asFile, session)
      }
    }
  }
}
EOF

echo "wrote ${OVERRIDE#"$ROOT"/} ${INIT_SCRIPT#"$ROOT"/}"

LOG="$OVERRIDE_DIR/podman.log"
LOG_LINES="${LOG_LINES:-2000}"

# Appends compose output to LOG, which is truncated on every launch. Lines are
# prefixed with the service name.
#
# `logs -f` fails until the containers exist and ends when they stop, so keep
# retrying. Containers and their history are reused across runs, so the first
# connect replays only the last LOG_LINES lines per container. Once something
# has been logged, reconnects only fetch output since the previous disconnect,
# so nothing is appended twice (bar lines within the same second).
follow_logs() {
  local from=(--tail "$LOG_LINES")
  while :; do
    # shellcheck disable=SC2086
    $COMPOSE -f compose.yaml -f "$OVERRIDE" logs -f "${from[@]}" \
      2>/dev/null \
      | sed -u 's/\x1b\[[0-9;]*m//g' >> "$LOG" || true
    [[ -s "$LOG" ]] && from=(--since "$(date -u +%Y-%m-%dT%H:%M:%SZ)")
    sleep 2
  done
}

cd "$ROOT"
: > "$LOG"
# Word splitting on COMPOSE is intended, it may be a multi word command.
# shellcheck disable=SC2086
$COMPOSE -f compose.yaml -f "$OVERRIDE" build "$SERVICE"

# No exec here, the script has to outlive `up` to stop the log follower.
#
# set -m starts the follower in its own process group, so one kill reaches the
# loop and everything under it, including the provider `podman compose` forks.
# Killing only direct children missed those and raced the loop starting its
# next `logs -f`, leaving followers that appended every line twice.
set -m
follow_logs < /dev/null &
LOGGER=$!
set +m
trap 'kill -- -"$LOGGER" 2>/dev/null' EXIT
echo "compose output: ${LOG#"$ROOT"/}"
# shellcheck disable=SC2086
$COMPOSE -f compose.yaml -f "$OVERRIDE" up "$@"
